import 'dart:io';

import 'package:flutter/material.dart';
import 'package:path_provider/path_provider.dart';
import 'package:share_plus/share_plus.dart';

import '../api_client.dart';
import '../models.dart';
import '../services.dart';
import '../widgets.dart';

/// Screen 8: the stored minutes for one meeting, with export (PDF / text).
class MinutesScreen extends StatefulWidget {
  const MinutesScreen({super.key, required this.meetingId, required this.serverUrl});
  final String meetingId, serverUrl;

  @override
  State<MinutesScreen> createState() => _MinutesScreenState();
}

class _MinutesScreenState extends State<MinutesScreen> {
  Minutes? _minutes;
  String? _error;
  bool _loading = true, _exporting = false;
  ApiClient? _api;

  @override
  void didChangeDependencies() {
    super.didChangeDependencies();
    if (_api != null) return;
    _api = Services.of(context).api(widget.serverUrl);
    _load();
  }

  @override
  void dispose() {
    _api?.close();
    super.dispose();
  }

  Future<void> _load() async {
    setState(() {
      _loading = true;
      _error = null;
    });
    try {
      final m = await _api!.minutes(widget.meetingId);
      if (mounted) setState(() => _minutes = m);
    } on ApiException catch (e) {
      if (mounted) setState(() => _error = e.message);
    } finally {
      if (mounted) setState(() => _loading = false);
    }
  }

  Future<void> _export(String format) async {
    setState(() => _exporting = true);
    try {
      final bytes = await _api!.export(widget.meetingId, format);
      final dir = await getTemporaryDirectory();
      // Dart's \w is ASCII-only, so a title in another script collapses to underscores: fall back to a plain name.
      final safe = (_minutes?.title ?? 'meeting').replaceAll(RegExp(r'[^\w\-]+'), '_').replaceAll(RegExp(r'^_+|_+$'), '');
      final file = File('${dir.path}/${safe.isEmpty ? 'meeting' : safe}_minutes.$format');
      await file.writeAsBytes(bytes, flush: true);
      await Share.shareXFiles([XFile(file.path, mimeType: format == 'pdf' ? 'application/pdf' : 'text/plain')], subject: '${_minutes?.title ?? 'Meeting'} minutes');
    } on ApiException catch (e) {
      if (mounted) toast(context, e.message);
    } on FileSystemException {
      if (mounted) toast(context, 'Could not save the export file on this device.');
    } catch (_) {
      if (mounted) toast(context, 'The file could not be shared. Try again.');
    } finally {
      if (mounted) setState(() => _exporting = false);
    }
  }

  @override
  Widget build(BuildContext context) {
    final m = _minutes;
    return Scaffold(
      appBar: AppBar(
        title: const Text('Meeting Minutes'),
        actions: [
          if (m != null)
            PopupMenuButton<String>(
              icon: _exporting ? const SizedBox(width: 20, height: 20, child: CircularProgressIndicator(strokeWidth: 2)) : const Icon(Icons.ios_share),
              tooltip: 'Export',
              enabled: !_exporting,
              onSelected: _export,
              itemBuilder: (_) => const [
                PopupMenuItem(value: 'pdf', child: Text('Export as PDF')),
                PopupMenuItem(value: 'txt', child: Text('Export as text')),
              ],
            ),
        ],
      ),
      body: SafeArea(
        child: _loading
            ? const Center(child: CircularProgressIndicator())
            : m == null
                ? Padding(padding: const EdgeInsets.all(16), child: ErrorBanner(_error ?? 'Minutes could not be loaded.', onRetry: _load))
                : _content(m),
      ),
    );
  }

  /// "Source: Alice · from 02:15" under an item, so every point can be traced back to the transcript.
  List<Widget> _source(Minutes m, List<int> ids, TextTheme t) {
    final label = m.sourceOf(ids);
    return label == null ? const [] : [Text('Source: $label', style: t.bodySmall)];
  }

  Widget _content(Minutes m) {
    final t = Theme.of(context).textTheme;
    return ListView(padding: const EdgeInsets.all(16), children: [
      if (m.warnings.isNotEmpty)
        SectionCard(title: 'Notes on this document', icon: Icons.info_outline, child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [for (final w in m.warnings) Text('• $w')])),
      SectionCard(
        title: 'Meeting Details',
        icon: Icons.event_note_outlined,
        child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
          Text(m.title, style: t.titleMedium),
          const SizedBox(height: 6),
          Text('Date: ${formatDateTime(m.date)}'),
          Text('Duration: ${formatDuration(m.durationSeconds)}'),
          Text('Participants: ${m.participants.isEmpty ? 'Not available' : m.participants.join(', ')}'),
          if (m.generatedBy.isNotEmpty) Text('Generated by: ${m.generatedBy == 'llm' ? 'AI model' : 'rule-based extraction'}', style: t.bodySmall),
        ]),
      ),
      SectionCard(title: 'Meeting Summary', icon: Icons.summarize_outlined, child: Text(m.summary.isEmpty ? 'No summary was generated.' : m.summary)),
      SectionCard(
        title: 'Key Discussion Points',
        icon: Icons.forum_outlined,
        child: m.keyPoints.isEmpty
            ? const Text('No key points were identified.')
            : Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                for (final k in m.keyPoints)
                  Padding(padding: const EdgeInsets.only(bottom: 10), child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                    Text(k.topic, style: t.titleSmall?.copyWith(fontWeight: FontWeight.w600)),
                    Text(k.details),
                    ..._source(m, k.segmentIds, t),
                  ])),
              ]),
      ),
      SectionCard(
        title: 'Decisions Made',
        icon: Icons.gavel_outlined,
        child: m.decisions.isEmpty
            ? const Text('No explicit decisions were identified.')
            : Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                for (final d in m.decisions)
                  Padding(padding: const EdgeInsets.only(bottom: 12), child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                    Text(d.description, style: t.bodyLarge?.copyWith(fontWeight: FontWeight.w600)),
                    Text('Responsible: ${d.speaker ?? 'Not identified'}', style: t.bodySmall),
                    if (d.context.isNotEmpty) Text('Context: ${d.context}'),
                    if (d.evidence.isNotEmpty) Text('"${d.evidence}"', style: t.bodySmall?.copyWith(fontStyle: FontStyle.italic)),
                    ..._source(m, d.segmentIds, t),
                  ])),
              ]),
      ),
      SectionCard(
        title: 'Action Items',
        icon: Icons.task_alt_outlined,
        child: m.actionItems.isEmpty
            ? const Text('No action items were identified.')
            : Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                for (final a in m.actionItems)
                  Padding(padding: const EdgeInsets.only(bottom: 12), child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                    Text(a.task, style: t.bodyLarge?.copyWith(fontWeight: FontWeight.w600)),
                    Text('Assigned to: ${a.assignee ?? 'Unassigned'}'),
                    Text('Deadline: ${a.deadline ?? 'Unspecified'}'),
                    Text('Status: ${a.status}', style: t.bodySmall),
                    if (a.evidence.isNotEmpty) Text('"${a.evidence}"', style: t.bodySmall?.copyWith(fontStyle: FontStyle.italic)),
                    ..._source(m, a.segmentIds, t),
                  ])),
              ]),
      ),
      SectionCard(
        title: 'Full Transcript',
        icon: Icons.notes_outlined,
        child: m.transcript.isEmpty
            ? const Text('No transcript is available.')
            : Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                for (final l in m.transcript)
                  Padding(padding: const EdgeInsets.only(bottom: 8), child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
                    Text('[${formatClock(l.start)}] ${l.speaker}', style: t.labelMedium?.copyWith(fontWeight: FontWeight.w600)),
                    Text(l.uncertain ? '${l.text}  (uncertain)' : l.text),
                  ])),
              ]),
      ),
    ]);
  }
}
